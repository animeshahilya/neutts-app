import java.util.Properties

// Same arrangement as the other apps in this workspace: real signing credentials live in an
// untracked keystore.properties, and the release build falls back to unsigned when it is absent so
// a clean checkout still builds.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) keystorePropertiesFile.inputStream().use { load(it) }
}

plugins {
  alias(libs.plugins.android.application)
  alias(libs.plugins.compose.compiler)
  alias(libs.plugins.kotlin.serialization)
}

android {
    namespace = "com.animeshahilya.neutts"
    compileSdk {
        version = release(37) { minorApiLevel = 2 }
    }
    ndkVersion = "30.0.16248370"
    defaultConfig {
        applicationId = "com.animeshahilya.neutts"
        minSdk = 24
        targetSdk = 37
        versionCode = 2
        versionName = "1.1.0"
        
        ndk {
            abiFilters.add("arm64-v8a")
        }
        
        externalNativeBuild {
            cmake {
                // Vulkan compute backend for llama.cpp. Generation is the app's bottleneck - on a
                // Pixel 8 the CPU manages a real-time factor of about 2.5 - and the GPU is the only
                // remaining lever of that size. Off if the toolchain cannot build it: the shaders
                // are generated by a host-side tool during cross-compilation, which needs a Windows
                // compiler on PATH (an MSVC environment), so this is opt-in via -PvulkanBackend.
                if (project.hasProperty("vulkanBackend")) {
                    arguments += listOf(
                        "-DGGML_VULKAN=ON",
                        "-DVulkan_GLSLC_EXECUTABLE=" + (System.getenv("NDK_GLSLC") ?: "glslc"),
                        // ggml-vulkan requires the SPIRV-Headers CMake package but only wants the
                        // headers; the NDK already ships them, so a small config shim points there
                        // rather than vendoring a second copy or requiring the Vulkan SDK.
                        "-DSPIRV-Headers_DIR=" + file("src/main/cpp/cmake/spirv-headers").absolutePath,
                        "-DVULKAN_HPP_INCLUDE_DIR=" + (System.getenv("VULKAN_HPP_DIR") ?: ""),
                        "-DSPIRV_HEADERS_INCLUDE_DIR=" + (System.getenv("SPIRV_HEADERS_DIR") ?: ""),
                    )
                }
                cppFlags("-std=c++17 -O3")
                arguments("-DANDROID_STL=c++_shared")
            }
        }
    }

    signingConfigs {
        if (keystorePropertiesFile.exists()) {
            create("release") {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            if (keystorePropertiesFile.exists()) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    buildFeatures {
      compose = true
      aidl = false
      buildConfig = false
      shaders = false
    }
    
    externalNativeBuild {
        cmake {
            path("src/main/cpp/CMakeLists.txt")
            version = "3.22.1+"
        }
    }

    packaging {
      resources {
        excludes += "/META-INF/{AL2.0,LGPL2.1}"
      }
    }
    
    androidResources {
        noCompress += "gguf"
        noCompress += "onnx"
    }
}

